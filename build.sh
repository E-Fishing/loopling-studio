#!/bin/sh
# Joins src/ into one self-contained page: loopling-studio.html
# Voice clips in voice/ (named like L1-S1-1.mp3, see voiceover-script.md) and instrument recordings
# in inst/<preset>/ (named like C4.mp3, Fs4.wav; inst/kit/ uses drum row names) are listed automatically.
cd "$(dirname "$0")"
# .m4a is MP4 audio under another name; artifacts serve .mp4, so rename (the bytes stay the same)
for f in voice/*.m4a; do [ -e "$f" ] && mv "$f" "${f%.m4a}.mp4"; done
# entries DIR: prints '"id": "path",' lines for the audio files in DIR
entries() {
  for f in "$1"/*.mp3 "$1"/*.mp4 "$1"/*.wav "$1"/*.ogg "$1"/*.webm; do
    [ -e "$f" ] || continue
    id=$(basename "$f"); id="${id%.*}"
    printf '\n  "%s": "%s",' "$id" "$f"
  done
}
{
  echo '// Generated by build.sh from the voice/ folder. Do not edit.'
  printf 'const VO_FILES = {'; entries voice; printf '\n};\n'
} > src/15-voice-files.js
{
  echo '// Generated by build.sh from the inst/ folders. Do not edit.'
  printf 'const INST_FILES = {'
  for d in inst/*/; do
    d=${d%/}
    printf '\n "%s": {' "$(basename "$d")"; entries "$d" | sed 's/^/ /'; printf '\n },'
  done
  printf '\n};\n'
} > src/16-inst-files.js
JS="src/10-core.js src/12-icons.js src/15-voice-files.js src/16-inst-files.js src/20-audio.js src/22-samples.js
    src/30-ui.js src/40-editors.js src/50-lessons.js src/55-guide.js src/56-voice.js src/60-main.js"
# loopling-studio.html: the page body for the claude.ai artifact (which adds the document skeleton itself)
{
  cat src/01-head.html src/02-body.html
  echo '<script>'
  cat $JS
  echo '</script>'
} > loopling-studio.html
# index.html: the same app as a complete web page, for GitHub Pages or any other web host
{
  cat <<'EOF'
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="description" content="Loopling Studio: a free music maker that teaches you how music software (DAWs) works, one small step at a time.">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Crect x='6' y='2' width='20' height='28' rx='6' fill='%232B4FE0'/%3E%3Ccircle cx='16' cy='8.5' r='2.6' fill='%23fff'/%3E%3Ccircle cx='16' cy='19.5' r='6.2' fill='%23fff'/%3E%3Ccircle cx='16' cy='19.5' r='2.6' fill='%23151823'/%3E%3C/svg%3E">
<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top);padding-bottom:env(safe-area-inset-bottom)}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style>
EOF
  grep -v 'claude:viewport' src/01-head.html
  echo '</head>'
  echo '<body>'
  cat src/02-body.html
  echo '<script>'
  cat $JS
  echo '</script>'
  echo '</body>'
  echo '</html>'
} > index.html
echo "built loopling-studio.html ($(wc -c < loopling-studio.html) bytes) and index.html, voice clips: $(grep -c '": "voice/' src/15-voice-files.js), instrument recordings: $(grep -c '": "inst/' src/16-inst-files.js)"
